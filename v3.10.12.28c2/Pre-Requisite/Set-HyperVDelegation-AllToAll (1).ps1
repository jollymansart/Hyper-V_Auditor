<#
.SYNOPSIS
    Set-HyperVDelegation-AllToAll.ps1
    Configures Kerberos delegation (RBCD or KCD) between ALL Hyper-V hosts so
    any host can live-migrate VMs to any other host.

.DESCRIPTION
    This is Step 1 of a two-step Kerberos live migration setup:

      Step 1 (THIS SCRIPT): Configure delegation trust in Active Directory
      Step 2 (Set-HyperVKerberosLiveMigration.ps1): Set each host's auth type to Kerberos

    Running Step 2 without Step 1 will BREAK live migration because the hosts
    will attempt Kerberos auth but no delegation trust exists in AD.

    This script is a "catch-all" -- it configures EVERY host to delegate to
    EVERY other host in the scope. This ensures live migration works in any
    direction without analyzing individual gaps first. For surgical gap-fixing
    based on the Hyper-V Inventory Report's KCD-Validation tab findings, use
    the per-host remediation scripts generated by the report instead (OPEN-61).

    TWO MODES
    ---------
    RBCD (default, recommended for Server 2012+):
      - Configures msDS-AllowedToActOnBehalfOfOtherIdentity on each DESTINATION host
      - The destination host controls who can delegate TO it
      - Does NOT require Domain Admin -- only requires write access to the
        destination host's AD computer object (Hyper-V Admins can do this)
      - Preferred approach per Microsoft documentation

    KCD (legacy, for pre-2012 or mixed environments):
      - Configures msDS-AllowedToDelegateTo on each SOURCE host
      - The source host's AD object lists which SPNs it can delegate TO
      - REQUIRES Domain Admin to modify the delegation properties
      - SPNs configured: cifs/<dest> and Microsoft Virtual System Migration Service/<dest>
        for both short name and FQDN of each destination

    WHAT THIS SCRIPT CONFIGURES
    ---------------------------
    For N hosts in scope, this script creates N*(N-1) delegation relationships
    (every host to every other host, bidirectional). For example:
      3 hosts (A, B, C) = 6 relationships: A->B, A->C, B->A, B->C, C->A, C->B

    The script is ADDITIVE -- it adds delegation entries without removing existing
    ones. Running it multiple times is safe (idempotent for RBCD; additive-safe
    for KCD since duplicate SPNs are harmless).

.PARAMETER Mode
    Delegation mode: 'RBCD' (default) or 'KCD'.
    RBCD is recommended for all Server 2012+ environments.

.PARAMETER ComputerName
    One or more Hyper-V host names or FQDNs.
    If omitted, auto-discovers from Active Directory using the same
    SPN-based detection as the Hyper-V Inventory Report (with CR110
    CNO/AG-listener filtering applied).

.PARAMETER ClusterName
    Optional: scope discovery to a single failover cluster.
    Uses Get-ClusterNode to enumerate only the nodes in that cluster.
    Mutually exclusive with -ComputerName.

.PARAMETER Credential
    PSCredential for AD operations. For RBCD, needs write access to
    destination host computer objects. For KCD, needs Domain Admin.
    If omitted, uses the current user context.

.PARAMETER Domain
    AD domain to query. Default: ohdc.com

.PARAMETER LogPath
    Directory for the change log CSV. Default: script directory.

.PARAMETER WhatIf
    Dry-run mode. Reports what WOULD be configured without making changes.

.PARAMETER Force
    Suppress confirmation prompts.

.EXAMPLE
    # Dry run -- see what would be configured (RBCD mode, all hosts)
    .\Set-HyperVDelegation-AllToAll.ps1 -WhatIf

.EXAMPLE
    # Configure RBCD for all hosts in the MHOHCLUHV cluster
    .\Set-HyperVDelegation-AllToAll.ps1 -ClusterName MHOHCLUHV -Force

.EXAMPLE
    # Configure KCD (legacy) for specific hosts
    .\Set-HyperVDelegation-AllToAll.ps1 -Mode KCD -ComputerName RICTX-HV-P01,RICTX-HV-P02 -Force

.EXAMPLE
    # Full environment RBCD configuration with credential prompt
    $cred = Get-Credential
    .\Set-HyperVDelegation-AllToAll.ps1 -Credential $cred -Force

